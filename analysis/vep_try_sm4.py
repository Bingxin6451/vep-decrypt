def rotl(x, n):
    return ((x << n) | (x >> (32-n))) & 0xffffffff

def sm4_round(x0,x1,x2,x3,rk):
    t = (x1 ^ x2 ^ x3 ^ rk) & 0xffffffff
    b = bytes([(t>>24)&0xff,(t>>16)&0xff,(t>>8)&0xff,t&0xff])
    sub = bytes([SBOX[b[0]],SBOX[b[1]],SBOX[b[2]],SBOX[b[3]]])
    t2 = struct.unpack('>I', sub)[0]
    t3 = t2 ^ rotl(t2,2) ^ rotl(t2,10) ^ rotl(t2,18) ^ rotl(t2,24)
    return x0 ^ t3

def sm4_setkey(key):
    MK = struct.unpack('>IIII', key)
    K = [MK[i] ^ FK[i] for i in range(4)]
    rk = []
    for i in range(32):
        t = (K[i+1] ^ K[i+2] ^ K[i+3] ^ CK[i]) & 0xffffffff
        b = bytes([(t>>24)&0xff,(t>>16)&0xff,(t>>8)&0xff,t&0xff])
        sub = bytes([SBOX[b[0]],SBOX[b[1]],SBOX[b[2]],SBOX[b[3]]])
        t2 = struct.unpack('>I', sub)[0]
        t3 = t2 ^ rotl(t2,13) ^ rotl(t2,23)
        K.append(K[i] ^ t3)
        rk.append(K[i+4])
    return rk

def sm4_enc_block(rk, block):
    x = struct.unpack('>IIII', block)
    for i in range(32):
        x0,x1,x2,x3 = x
        nx = sm4_round(x0,x1,x2,x3,rk[i])
        x = (x1,x2,x3,nx)
    x = (x[3],x[2],x[1],x[0])
    return struct.pack('>IIII', *x)

def sm4_ctr_stream(key, nonce, nblocks):
    rk = sm4_setkey(key)
    out = bytearray()
    ctr = struct.unpack('>I', nonce[12:16])[0] if len(nonce) == 16 else 0
    for i in range(nblocks):
        blk = nonce[:12] + struct.pack('>I', ctr + i)
        out += sm4_enc_block(rk, blk)
    return bytes(out)

